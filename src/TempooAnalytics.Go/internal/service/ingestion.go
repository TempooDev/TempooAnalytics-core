type AnalyticsEventDto struct {
	SiteId    string       `json:"siteId"` //represent siteKey important
	Type      string       `json:"type"` // pageview, custom, etc.
	Url       string       `json:"url"`
	Title     string       `json:"title"`     // optional
	Referrer  string       `json:"referrer"`
	Viewport  *ViewportDto `json:"viewport"`  // optional
	Screen    *ViewportDto `json:"screen"`    // optional real screen resolution
	VisitorId string       `json:"visitorId"` // optional
	SessionId string       `json:"sessionId"` // optional
	UserId    string       `json:"userId"`    // optional
	EventName string       `json:"eventName"` // optional
	Data      any          `json:"data"`      // optional
	Timestamp string       `json:"timestamp"` // optional
	UserAgent string       `json:"userAgent"` // optional override
	// EventId is generated by the tracker (UUID v7) and kept across retries: an event_id already accepted
	// in the last DedupTTL is answered 202 without storing it again. Optional; without it the server
	// generates one and cannot deduplicate.
	EventId string `json:"eventId"`
}

type ViewportDto struct {
	Width  int `json:"width"`
	Height int `json:"height"`
}

type EnrichedEvent struct {
	CountryCode    string
	CityName       string
	ASN            uint32
	Path           string
	ReferrerDomain string
	BrowserName    string
	OSInfo         string
	DeviceType     string
	TrafficType    int8
	BotName        string
	CompanyName    string
	CompanyDomain  string
}

// Interfaces to decouple
type EventRepository interface {
	InsertEvent(ctx context.Context, event *model.AnalyticsEvent) error
	InsertHeatmapClicks(ctx context.Context, clicks []*model.HeatmapClick) error
	MonthlyEventCounter
	Close() error
}

// DefaultDedupTTL is the default of IngestionService.DedupTTL.
const DefaultDedupTTL = 10 * time.Minute

// DefaultDependencyTimeout is the default of IngestionService.DependencyTimeout (INGEST_DEPENDENCY_TIMEOUT).
// 150 ms was too tight for a cold site lookup (Redis miss plus a Postgres query over a WAN link, possibly on a
// new connection): events were answered 503. The site config is also preloaded, so this is a safety net.
const DefaultDependencyTimeout = 500 * time.Millisecond

// ErrDependencyUnavailable: a dependency the event cannot do without (the site config) failed or timed out.
// The handler answers 503 with Retry-After.
var ErrDependencyUnavailable = errors.New("dependency unavailable")

// ErrOverloaded: ingestion has no room for the event right now (buffer full or too many requests in
// flight). The handler answers 503 with Retry-After.
var ErrOverloaded = errors.New("ingestion overloaded")

// withDependencyTimeout bounds a dependency call made while the client waits.
func (s *IngestionService) withDependencyTimeout(ctx context.Context) (context.Context, context.CancelFunc) {
	if s.DependencyTimeout <= 0 {
		return context.WithCancel(ctx)
	}
	return context.WithTimeout(ctx, s.DependencyTimeout)
}

type SiteRepository interface {
	GetSiteConfig(ctx context.Context, siteKey string, writeKey string) (*repository.SiteConfig, error)
}

type IngestionService struct {
	eventRepo EventRepository
	siteRepo  SiteRepository
	geo       *geoip2.Reader
	asn       *geoip2.Reader
	redis     *redis.Client // Optional, for cache if needed, though siteRepo handles its own cache
	quota     *QuotaCounter

	// DedupTTL is how long an accepted event_id is remembered to drop client retries (INGEST_DEDUP_TTL).
	// 0 disables deduplication.
	DedupTTL time.Duration

	// DependencyTimeout bounds each dependency call in the request path (site config, quota, heatmap
	// limits). Past it, the quota is skipped (fail-open) and an unresolved site config is a 503.
	DependencyTimeout time.Duration

	// HeatmapsEnabled turns heatmap ingestion on (FEATURE_HEATMAPS). Off, heatmap batches are dropped.
	HeatmapsEnabled bool

	// RequireWriteKey makes the site's write key mandatory (INGEST_REQUIRE_WRITE_KEY, off by default): a missing
	// or wrong key is a 401 even from an allowed origin. Off, an allowed Origin/Referer still lets in an event
	// without a valid key (sites whose key was revoked or rotated keep sending with the old snippet); those
	// events are counted in ingestion_origin_only_auth_total so the impact is known before turning it on.
	RequireWriteKey bool
	// heatmapAllow applies the heatmap ingestion limits. Tests replace it.
	heatmapAllow func(ctx context.Context, siteID, ipStr string, clicks int, monthlyLimit int64) bool
}

func NewIngestionService(eventRepo EventRepository, siteRepo SiteRepository, geo *geoip2.Reader, asn *geoip2.Reader, redis *redis.Client) *IngestionService {
	s := &IngestionService{
		eventRepo: eventRepo,
		siteRepo:  siteRepo,
		geo:       geo,
		asn:       asn,
		redis:     redis,
		quota:     NewQuotaCounter(redis, eventRepo),

		DependencyTimeout: DefaultDependencyTimeout,
		DedupTTL:          DefaultDedupTTL,
	}
	s.heatmapAllow = s.allowHeatmapBatch
	return s
}

func (s *IngestionService) enrichEvent(ipStr string, userAgentStr string, dto *AnalyticsEventDto, req *http.Request) EnrichedEvent {
	// We switch to := to declare the local variables
	countryCode := "XX"
	cityName := ""
	var asnNum uint32 = 0

	// GeoIP Enrichment CountryCode, CityName, ASN
	ip := net.ParseIP(ipStr)
	if ip != nil {
		if s.geo != nil {
			if record, err := s.geo.Country(ip); err == nil {
				countryCode = record.Country.IsoCode
			}
			if record, err := s.geo.City(ip); err == nil {
				cityName = record.City.Names["en"]
			}
		}
		if s.asn != nil {
			if record, err := s.asn.ASN(ip); err == nil {
				asnNum = uint32(record.AutonomousSystemNumber)
			}
		}
	}

	// Parse URL for domains
	parsedUrl, _ := url.Parse(dto.Url)
	path := "/"
	if parsedUrl != nil && parsedUrl.Path != "" {
		path = parsedUrl.Path
	}

	parsedReferrer, _ := url.Parse(dto.Referrer)
	referrerDomain := ""
	if parsedReferrer != nil {
		referrerDomain = parsedReferrer.Host
	}

	// Device/OS/Browser parsing
	ua := user_agent.New(userAgentStr)
	browserName, _ := ua.Browser()
	osInfo := ua.OS()
	deviceType := "desktop"
	if ua.Mobile() {
		deviceType = "mobile"
	} 

	var trafficType int8 = model.TrafficTypeHuman
	botName := ""
	
	lowerUA := strings.ToLower(userAgentStr)
	isBotDetected := ua.Bot() || strings.Contains(lowerUA, "bot") || strings.Contains(lowerUA, "spider") || strings.Contains(lowerUA, "crawler") || strings.Contains(lowerUA, "openai") || strings.Contains(lowerUA, "claude")
	
	if isBotDetected {
		deviceType = "bot"
		
		aiBots := map[string]string{
			"gptbot":            "GPTBot (OpenAI)",
			"chatgpt-user":      "ChatGPT-User",
			"oai-searchbot":     "OpenAI Search",
			"claude":            "Anthropic Claude",
			"anthropic":         "Anthropic Claude",
			"google-extended":   "Google Gemini",
			"googleagent":       "Google Agent",
			"googlebot":         "Googlebot",
			"bingbot":           "Bingbot",
			"perplexity":        "Perplexity AI",
			"applebot-extended": "Apple Intelligence",
			"applebot":          "Applebot",
			"meta-externalagent": "Meta AI",
			"cohere-ai":         "Cohere AI",
			"bytespider":        "ByteDance / TikTok",
			"ccbot":             "Common Crawl",
			"amazonbot":         "Amazonbot",
			"omgilibot":         "Omgili (Webz.io)",
			"yandexbot":         "YandexBot",
			"baiduspider":       "BaiduSpider",
			"slackbot":          "Slackbot",
			"twitterbot":        "X / TwitterBot",
			"facebookexternalhit": "Meta / Facebook",
			"linkedinbot":       "LinkedInBot",
			"discordbot":        "DiscordBot",
			"telegrambot":       "TelegramBot",
		}

		isAI := false
		for pattern, name := range aiBots {
			if strings.Contains(lowerUA, pattern) {
				botName = name
				// Check if it's an AI bot (most of the modern high-value ones)
				if strings.Contains(pattern, "gpt") || 
				   strings.Contains(pattern, "oai-searchbot") ||
				   strings.Contains(pattern, "claude") || 
				   strings.Contains(pattern, "perplexity") || 
				   strings.Contains(pattern, "google-extended") ||
				   strings.Contains(pattern, "googleagent") ||
				   strings.Contains(pattern, "meta-") ||
				   strings.Contains(pattern, "anthropic") ||
				   strings.Contains(pattern, "cohere") ||
				   strings.Contains(pattern, "applebot-extended") ||
				   strings.Contains(pattern, "bytespider") ||
				   strings.Contains(pattern, "ccbot") ||
				   strings.Contains(pattern, "amazonbot") ||
				   strings.Contains(pattern, "omgilibot") {
					isAI = true
				}
				break
			}
		}

		if botName == "" {
			// Fallback: try to extract something from UA
			botName, _ = ua.Browser()
			if botName == "" {
				botName = "Generic Crawler"
			}
		}

		if isAI {
			trafficType = model.TrafficTypeBotIA
		} else {
			trafficType = model.TrafficTypeCrawler
		}
	}

	return EnrichedEvent{
		CountryCode:    countryCode,
		CityName:       cityName,
		ASN:            asnNum,
		Path:           path,
		ReferrerDomain: referrerDomain,
		BrowserName:    browserName,
		OSInfo:         osInfo,
		DeviceType:     deviceType,
		TrafficType:    trafficType,
		BotName:        botName,
		CompanyName:    "", // Future enrichment
		CompanyDomain:  "", // Future enrichment
	}
}

func (s *IngestionService) ProcessEvent(ctx context.Context, dto *AnalyticsEventDto, req *http.Request) error {
	// Once started, an event is processed to the end even if the client disconnects: otherwise a client
	// that gives up (timeout) cancels the deduplication and quota calls halfway, the event is stored
	// anyway, and its retry is stored again. Each dependency call has its own DependencyTimeout instead.
	ctx = context.WithoutCancel(ctx)

	// 1. Authorization Check & Resolve Site Config
	// siteKey can be a UUID or a SiteKey string
	providedWriteKey := extractWriteKey(req)
	siteCtx, siteSpan := startStep(ctx, "ingest.site_config", attribute.String("tempoo.site_key", dto.SiteId))
	siteCtx, cancelSite := s.withDependencyTimeout(siteCtx)
	siteStart := time.Now()
	config, err := s.siteRepo.GetSiteConfig(siteCtx, dto.SiteId, providedWriteKey)
	siteElapsed := time.Since(siteStart)
	cancelSite()
	endStep(siteSpan, ignoreNotFound(err))
	if errors.Is(err, repository.ErrSiteNotFound) {
		return fmt.Errorf("site configuration not found for %s: %w", dto.SiteId, ErrSiteNotFound)
	}
	if err != nil {
		// Could not validate the site: answer fast so the client retries, never hang the request.
		// Name the dependency and how long it took against its budget, so a timeout is diagnosable from the log.
		return fmt.Errorf("site lookup failed for %s (dependency=site_config elapsed=%s timeout=%s): %v: %w",
			dto.SiteId, siteElapsed.Round(time.Millisecond), s.DependencyTimeout, err, ErrDependencyUnavailable)
	}
	if config == nil {
		return fmt.Errorf("site configuration not found for %s: %w", dto.SiteId, ErrSiteNotFound)
	}

	// 1.1 Authorize
	if err := s.authorizeRequest(config, providedWriteKey, req); err != nil {
		return err
	}

	// 1.15 Trial Check
	if config.Plan == "free" {
		daysSinceCreation := time.Since(config.UserCreatedAt).Hours() / 24
		if daysSinceCreation >= 15 {
			return ErrTrialExpired
		}
	}

	// 1.16 Heatmap batches go to heatmap_clicks: no quota, no events row, no visitor hash.
	if dto.Type == heatmapEventType {
		return s.processHeatmap(ctx, dto, config, getIP(req), getUserAgent(dto.UserAgent, req))
	}

	// 1.2 Quota Check: Redis counter per site and month. Without Redis, or when it fails, the event is
	// accepted (fail-open); QuotaCounter logs that with a rate limit.
	quotaCtx, quotaSpan := startStep(ctx, "ingest.quota", attribute.String("tempoo.site_id", config.ID))
	quotaCtx, cancelQuota := s.withDependencyTimeout(quotaCtx)
	decision, quotaErr := s.quota.Check(quotaCtx, config.ID, config.MaxMonthlyEvents, 1)
	cancelQuota()
	quotaSpan.SetAttributes(attribute.String("tempoo.quota.decision", decision.String()))
	endStep(quotaSpan, quotaErr)
	metrics.QuotaDecisions.WithLabelValues(decision.String()).Inc()
	if decision == QuotaBlocked {
		ttlCtx, cancelTTL := s.withDependencyTimeout(ctx)
		defer cancelTTL()
		return &QuotaExceededError{RetryAfter: s.quota.BlockedFor(ttlCtx, config.ID)}
	}

	// 2. Extract IP and User Agent
	ipStr := getIP(req)
	userAgentStr := getUserAgent(dto.UserAgent, req)

	// 2.1 Determine Timestamp
	eventTimestamp := time.Now().UTC()
	if dto.Timestamp != "" {
		if t, err := time.Parse(time.RFC3339, dto.Timestamp); err == nil {
			eventTimestamp = t.UTC()
		}
	}
	eventDate := time.Date(eventTimestamp.Year(), eventTimestamp.Month(), eventTimestamp.Day(), 0, 0, 0, 0, time.UTC)

	// 3. Privacy Hash (Uses event timestamp for consistent monthly salt)
	userHash := generateUserHash(ipStr, userAgentStr, eventTimestamp)

	// 4. Enrichment
	enriched := s.enrichEvent(ipStr, userAgentStr, dto, req)

	// 5. Construct Event
	sessionUUID, _ := uuid.Parse(dto.SessionId)
	if sessionUUID == uuid.Nil {
		sessionUUID = uuid.New()
	}
	siteUUID, _ := uuid.Parse(config.ID) // config.ID is the real UUID from Postgres

	// Prepare data JSON - embed page title there
	dataMap := make(map[string]any)
	if dto.Data != nil {
		if jData, ok := dto.Data.(map[string]any); ok {
			dataMap = jData
		} else if sData, ok := dto.Data.(string); ok {
			_ = json.Unmarshal([]byte(sData), &dataMap)
		}
	}
	if dto.Title != "" {
		dataMap["page_title"] = dto.Title
	}

	var dataStr string = "{}"
	if len(dataMap) > 0 {
		if jData, err := json.Marshal(dataMap); err == nil {
			dataStr = string(jData)
		}
	}

	eventID, clientEventID := parseClientEventID(dto.EventId)
	event := &model.AnalyticsEvent{
		EventID:        eventID,
		SiteID:         siteUUID,
		UserHash:       userHash,
		VisitorID:      dto.VisitorId,
		SessionID:      sessionUUID,
		Timestamp:      eventTimestamp,
		Date:           eventDate,
		CountryCode:    enriched.CountryCode,
		CityName:       enriched.CityName,
		DeviceType:     enriched.DeviceType,
		OS:             enriched.OSInfo,
		Browser:        enriched.BrowserName,
		Referrer:       dto.Referrer,
		ReferrerDomain: enriched.ReferrerDomain,
		UtmSource:      getQueryParam(dto.Url, "utm_source"),
		UtmMedium:      getQueryParam(dto.Url, "utm_medium"),
		UtmCampaign:    getQueryParam(dto.Url, "utm_campaign"),
		EventName:      dto.Type,
		Path:           enriched.Path,
		PageTitle:      dto.Title,
		TrafficType:    enriched.TrafficType,
		ASN:            enriched.ASN,
		UserAgent:      userAgentStr,
		BotName:        enriched.BotName,
		CompanyName:    enriched.CompanyName,
		CompanyDomain:  enriched.CompanyDomain,
		Data:           dataStr,
	}

	if event.VisitorID == "" {
		event.VisitorID = userHash
	}

	if dto.Screen != nil {
		event.ScreenWidth = uint16(dto.Screen.Width)
		event.ScreenHeight = uint16(dto.Screen.Height)
	} else if dto.Viewport != nil {
		event.ScreenWidth = uint16(dto.Viewport.Width)
		event.ScreenHeight = uint16(dto.Viewport.Height)
	}

	// Clicks on data-tempoo-goal arrive as type "goal" with the attribute value in eventName.
	if (dto.Type == "custom" || dto.Type == "goal") && dto.EventName != "" {
		event.EventName = dto.EventName
	}

	// 6. Deduplicate client retries by event_id, then save (async via worker).
	var dedupKey string
	if clientEventID {
		dedupCtx, dedupSpan := startStep(ctx, "ingest.dedup")
		first, key := s.claimEventID(dedupCtx, eventID)
		dedupSpan.SetAttributes(attribute.Bool("tempoo.event.duplicate", !first))
		endStep(dedupSpan, nil)
		if !first {
			if decision == QuotaAllowed {
				s.quota.Refund(ctx, config.ID, 1)
			}
			metrics.DuplicateEvents.Inc()
			return nil // already accepted: 202 again, nothing stored
		}
		dedupKey = key
	}
	enqueueCtx, enqueueSpan := startStep(ctx, "ingest.enqueue")
	err = s.eventRepo.InsertEvent(enqueueCtx, event)
	endStep(enqueueSpan, err)
	if err != nil {
		if decision == QuotaAllowed {
			s.quota.Refund(ctx, config.ID, 1)
		}
		if dedupKey != "" {
			// Not accepted after all: let the client's retry through.
			s.releaseEventID(dedupKey)
		}
		if errors.Is(err, repository.ErrBufferFull) {
			return fmt.Errorf("%w: %w", ErrOverloaded, err)
		}
		return err
	}
	return nil
}

// ignoreNotFound keeps an unknown site (the client's mistake) from marking the span as an error.
func ignoreNotFound(err error) error {
	if errors.Is(err, repository.ErrSiteNotFound) {
		return nil
	}
	return err
}

// parseClientEventID returns the client's event_id when it is a valid UUID (true), or a new random one.
func parseClientEventID(raw string) (uuid.UUID, bool) {
	if raw != "" {
		if id, err := uuid.Parse(raw); err == nil && id != uuid.Nil {
			return id, true
		}
	}
	return uuid.New(), false
}

// claimEventID records the event_id in Redis (SET NX evt:{id}, DedupTTL). It returns false when the id was
// already accepted. Without Redis, or when it fails or is slow, the event goes through (fail-open: at worst
// a retry is stored twice).
func (s *IngestionService) claimEventID(ctx context.Context, id uuid.UUID) (bool, string) {
	if s.redis == nil || s.DedupTTL <= 0 {
		return true, ""
	}
	key := "evt:" + id.String()
	dctx, cancel := s.withDependencyTimeout(ctx)
	defer cancel()
	first, err := s.redis.SetNX(dctx, key, 1, s.DedupTTL).Result()
	if err != nil {
		return true, ""
	}
	return first, key
}

// releaseEventID forgets an event_id that was claimed but not accepted (for example, buffer full).
func (s *IngestionService) releaseEventID(key string) {
	ctx, cancel := context.WithTimeout(context.Background(), time.Second)
	defer cancel()
	s.redis.Del(ctx, key)
}

// Quota returns the monthly quota counter, so main can run its reconciliation.
func (s *IngestionService) Quota() *QuotaCounter {
	return s.quota
}

func (s *IngestionService) authorizeRequest(config *repository.SiteConfig, providedWriteKey string, req *http.Request) error {
	// 1. Authorize: Check WriteKey if provided. A site without a key (revoked) matches no key.
	if providedWriteKey != "" && config.WriteKey != "" &&
		subtle.ConstantTimeCompare([]byte(providedWriteKey), []byte(config.WriteKey)) == 1 {
		return nil // Authorized by key
	}
	if s.RequireWriteKey {
		return ErrUnauthorized
	}

	// 2. Authorize: Check Origin if no key or key didn't match (fallback to origin-based)
	origin := extractOrigin(req)
	if origin != "" {
		if originAllowed(origin, config.AllowedOrigins) {
			reason := "missing_key"
			if providedWriteKey != "" {
				reason = "wrong_key"
			}
			metrics.OriginOnlyAuth.WithLabelValues(reason).Inc()
			return nil // Authorized by origin
		}
		if providedWriteKey != "" {
			return ErrUnauthorized // a wrong key is reported as such, even with an origin
		}
		return ErrOriginNotAllowed
	}

	return ErrUnauthorized
}

// Helper functions
func getIP(r *http.Request) string {
	// Priority: CF-Connecting-IP > X-Forwarded-For > RemoteAddr
	cfIP := r.Header.Get("CF-Connecting-IP")
	if cfIP != "" {
		return cfIP
	}
	forwarded := r.Header.Get("X-Forwarded-For")
	if forwarded != "" {
		// Can be comma separated
		ips := strings.Split(forwarded, ",")
		return strings.TrimSpace(ips[0])
	}

	// RemoteAddr usually contains port, strip it
	ip, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil {
		return r.RemoteAddr
	}
	return ip
}

func hash(s string) string {
	h := sha256.New()
	h.Write([]byte(s))
	return hex.EncodeToString(h.Sum(nil))
}

func getQueryParam(rawUrl, key string) string {
	u, err := url.Parse(rawUrl)
	if err != nil {
		return ""
	}
	return u.Query().Get(key)
}

func extractWriteKey(req *http.Request) string {
	if auth := req.Header.Get("Authorization"); strings.HasPrefix(auth, "Bearer ") {
		return strings.TrimPrefix(auth, "Bearer ")
	} else if apiKey := req.Header.Get("X-API-Key"); apiKey != "" {
		return apiKey
	} else {
		return req.URL.Query().Get("key")
	}
}

func extractOrigin(req *http.Request) string {
	origin := req.Header.Get("Origin")
	if origin == "" {
		origin = req.Header.Get("Referer")
	}
	return origin
}

// originAllowed reports whether the request origin (an Origin header or a full Referer URL) belongs to one of the
// site's allowed origins. Both sides are reduced to a hostname, so an allowed value may be stored with or without
// scheme, port, path or a leading "www." / "*.": the origin's host must equal the allowed host or be a subdomain of it.
// A plain substring test is not enough: "example.com" is inside "https://example.com.evil.io" and "https://notexample.com".
func originAllowed(origin string, allowedOrigins []string) bool {
	host := originHost(origin)
	if host == "" {
		return false
	}
	for _, allowed := range allowedOrigins {
		allowedHost := originHost(allowed)
		// "www." and "*." name the same site as the bare domain, which in turn allows its subdomains.
		allowedHost = strings.TrimPrefix(allowedHost, "*.")
		allowedHost = strings.TrimPrefix(allowedHost, "www.")
		if allowedHost == "" || strings.Contains(allowedHost, "*") {
			continue
		}
		if host == allowedHost || strings.HasSuffix(host, "."+allowedHost) {
			return true
		}
	}
	return false
}

// originHost returns the lowercase hostname of an origin or URL, without port or trailing dot. A value without a
// scheme ("example.com", "example.com:8080/path") is read as a host. It returns "" when no host can be read.
func originHost(value string) string {
	value = strings.TrimSpace(value)
	if value == "" {
		return ""
	}
	if !strings.Contains(value, "://") {
		value = "http://" + value
	}
	u, err := url.Parse(value)
	if err != nil {
		return ""
	}
	return strings.TrimSuffix(strings.ToLower(u.Hostname()), ".")
}

func generateUserHash(ipStr string, userAgentStr string, ts time.Time) string {
	// Use a monthly salt instead of daily to allow consistent unique visitor counting over time.
	// This balances privacy (hashes change every month) with utility (can count monthly uniques).
	salt := ts.UTC().Format("2006-01") 
	return hash(ipStr + userAgentStr + salt)
}

func getUserAgent(dtoUserAgent string, req *http.Request) string {
	if dtoUserAgent != "" {
		return dtoUserAgent
	}
	return req.UserAgent()
}

func (s *IngestionService) Close() error {
	return s.eventRepo.Close()
}
