// Builds the stylesheets of the admin console (Razor pages under /admin), so they need no third-party CDN at runtime.
// Run build.sh; it installs the pinned tools in a temporary folder and calls this script with ADMIN_ASSETS_TOOLS pointing there.
//   admin.css: Tailwind v3 utilities used by the pages + the PrimeIcons glyphs they use (inline SVG masks, no font file).
//   admin-font.css: Plus Jakarta Sans (latin, variable weight, SIL OFL 1.1) embedded as a data: URI.
// Output: src/TempooAnalytics.Api/Infrastructure/Admin/Assets/ (embedded resources of the API, inlined by AdminAssets).
import { promises as fs } from "fs";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const out = path.join(repo, "src/TempooAnalytics.Api/Infrastructure/Admin/Assets");
const tools = process.env.ADMIN_ASSETS_TOOLS;
if (!tools) throw new Error("ADMIN_ASSETS_TOOLS is not set: run build.sh");
const require = createRequire(path.join(tools, "index.js"));

const tailwindCss = await fs.readFile(process.argv[2], "utf8");

// The icons the pages use (class "pi pi-<name>"), found in the same files Tailwind scans (src/*/Pages).
const srcDir = path.join(repo, "src");
const pages = (await fs.readdir(srcDir)).map(p => path.join(srcDir, p, "Pages"));
const used = new Set();
for (const dir of pages) {
  let entries = [];
  try { entries = await fs.readdir(dir, { recursive: true }); } catch { continue; }
  for (const f of entries.filter(e => e.endsWith(".cshtml"))) {
    const text = await fs.readFile(path.join(dir, f), "utf8");
    for (const m of text.matchAll(/\bpi-([a-z0-9-]+)/g)) used.add(m[1]);
  }
}
const svgDir = path.join(path.dirname(require.resolve("primeicons/primeicons.css")), "raw-svg");
let icons = ".pi{display:inline-block;width:1em;height:1em;line-height:1;vertical-align:-.125em;background-color:currentColor;"
  + "-webkit-mask:var(--pi) center/contain no-repeat;mask:var(--pi) center/contain no-repeat}\n";
let glyphs = 0;
for (const name of [...used].sort()) {
  let svg;
  try { svg = await fs.readFile(path.join(svgDir, `${name}.svg`), "utf8"); } catch { continue; } // pi-fw, pi-spin...: not glyphs
  const uri = "data:image/svg+xml;base64," + Buffer.from(svg.trim()).toString("base64");
  icons += `.pi-${name}{--pi:url('${uri}')}\n`;
  glyphs++;
}

await fs.mkdir(out, { recursive: true });
const header = "/* Generated by scripts/admin-assets/build.sh: do not edit. Tailwind CSS v3 (MIT); PrimeIcons glyphs (MIT). */\n";
await fs.writeFile(path.join(out, "admin.css"), header + tailwindCss.trim() + "\n" + icons);

const fontDir = path.join(path.dirname(require.resolve("@fontsource-variable/plus-jakarta-sans/index.css")), "files");
const woff2 = await fs.readFile(path.join(fontDir, "plus-jakarta-sans-latin-wght-normal.woff2"));
const font = "/* Generated by scripts/admin-assets/build.sh: do not edit. Plus Jakarta Sans (SIL Open Font License 1.1), latin subset. */\n"
  + "@font-face{font-family:'Plus Jakarta Sans';font-style:normal;font-display:swap;font-weight:200 800;"
  + `src:url(data:font/woff2;base64,${woff2.toString("base64")}) format('woff2');`
  + "unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}\n";
await fs.writeFile(path.join(out, "admin-font.css"), font);
console.log(`admin.css (${glyphs} icons) and admin-font.css written to ${path.relative(repo, out)}`);
